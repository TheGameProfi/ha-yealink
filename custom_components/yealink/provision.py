"""Figure out how the phone reaches HA, and build a Yealink provisioning file."""
from __future__ import annotations

import socket
from urllib.parse import urlparse

from homeassistant.core import HomeAssistant

from .const import CONF_HA_URL, CONF_WEBHOOK_ID


def local_ip_towards(target_host: str) -> str | None:
    """IP of the interface the OS would use to reach the phone.
    UDP connect sends nothing, it only resolves the route."""
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
            s.connect((target_host, 9))
            return s.getsockname()[0]
    except OSError:
        return None


def ha_base_url(hass: HomeAssistant, entry) -> str:
    """Option override > route-based detection > HA's configured internal URL."""
    if url := entry.options.get(CONF_HA_URL):
        return url.rstrip("/")
    phone_host = urlparse(entry.runtime_data.base).hostname
    ip = local_ip_towards(phone_host) if phone_host else None
    port = hass.http.server_port if getattr(hass, "http", None) else 8123
    if ip:
        return f"http://{ip}:{port}"
    from homeassistant.helpers.network import NoURLAvailableError, get_url
    try:
        return get_url(hass, allow_external=False, prefer_external=False)
    except NoURLAvailableError:
        return f"http://HOME_ASSISTANT_IP:{port}"


def action_urls(base: str, webhook_id: str) -> dict[str, str]:
    hook = f"{base}/api/webhook/{webhook_id}"
    return {
        "incoming_call": f"{hook}?event=incoming&from=$remote&name=$display_remote",
        "outgoing_call": f"{hook}?event=outgoing&from=$remote&name=$display_remote",
        "call_established": f"{hook}?event=established",
        "call_terminated": f"{hook}?event=ended",
        "missed_call": f"{hook}?event=missed&from=$remote&name=$display_remote",
    }


def provisioning_file(base: str, entry) -> str:
    """Yealink auto-provisioning config: sets the Action URLs and the Action URI allow list."""
    lines = ["#!version:1.0.0.1", "## generated by Home Assistant (yealink integration)"]
    for key, url in action_urls(base, entry.data[CONF_WEBHOOK_ID]).items():
        lines.append(f"action_url.{key} = {url}")
    lines.append(f"features.action_uri_limit_ip = {urlparse(base).hostname}")
    return "\n".join(lines) + "\n"
